'use client';
import { useToast as useToastPrimitive } from '@/components/ui/toast';
import type { ToastActionElement } from '@radix-ui/react-toast';
type ToasterToast = { id: string; title?: string; description?: string; action?: ToastActionElement; variant?: 'default' | 'destructive' | 'success'; promise?: Promise<any>; };
type ToastProps = Omit<ToasterToast, 'id'>;
function useToast() {
  const { toast, dismiss } = useToastPrimitive();
  return {
    toast: (props: ToastProps) => { const { variant = 'default', ...rest } = props; return toast({ variant, ...rest }); },
    success: (props: Omit<ToastProps, 'variant'>) => { return toast({ variant: 'success', ...props }); },
    error: (props: Omit<ToastProps, 'variant'>) => { return toast({ variant: 'destructive', ...props }); },
    dismiss,
  };
}
export { useToast, type ToasterToast };
